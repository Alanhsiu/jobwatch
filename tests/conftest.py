@pytest.fixture
def bot(bare_state_dir, feed_file, http, clock):
    """bot(*flags, env=..., now=..., feed=..., state=...) -> exit code, running jobwatch.run with fakes.

    Request `state_dir` as well to get the relaxed feed-size config; `bare_state_dir` alone keeps the defaults.
    """
    def _run(*flags, env=None, now=FROZEN_NOW, feed=feed_file, state=bare_state_dir):
        argv = ["--state-dir", state, *flags]
        if feed:
            argv += ["--feed", feed]
        args = jobwatch.parse_args(argv)
        rt = jobwatch.Runtime(now=now, env=dict(env or {}), urlopen=http.urlopen, sleep=clock.sleep, monotonic=clock.monotonic)
