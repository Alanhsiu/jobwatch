class FakeResponse:
    def __init__(self, body):
        self.body = body

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        return False

    def read(self):
        return self.body


class FakeHTTP:
    """Scriptable urlopen. Outcomes: "ok" | ("ok", body_bytes) | ("http", code, body_dict[, headers]) | ("raise", exc)."""

    def __init__(self):
        self.telegram = []
        self.feed = []
        self.calls = []

    def urlopen(self, req, timeout=None):
        url = req.full_url
        if "api.telegram.org" in url:
            fields = dict(urllib.parse.parse_qsl(req.data.decode()))
            self.calls.append(("telegram", fields))
            outcome = self.telegram.pop(0) if self.telegram else "ok"
        else:
            self.calls.append(("feed", url))
            outcome = self.feed.pop(0) if self.feed else ("ok", b"[]")
        if outcome == "ok":
            return FakeResponse(b'{"ok":true,"result":{}}')
        kind = outcome[0]
        if kind == "ok":
            return FakeResponse(outcome[1])
        if kind == "http":
            headers = email.message.Message()
            for k, v in (outcome[3] if len(outcome) > 3 else {}).items():
                headers[k] = str(v)
            raise urllib.error.HTTPError(url, outcome[1], f"HTTP {outcome[1]}", headers,
                                         io.BytesIO(json.dumps(outcome[2]).encode()))
        raise outcome[1]

    def telegram_texts(self):
        return [f["text"] for kind, f in self.calls if kind == "telegram"]


class FakeClock:
    def __init__(self):
        self.t = 1000.0
        self.sleeps = []

    def monotonic(self):
        return self.t

    def sleep(self, seconds):
        self.sleeps.append(seconds)
        self.t += seconds


